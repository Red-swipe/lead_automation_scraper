"""Read-only lead and sending status; never prints key values."""
import os
from pathlib import Path
import pandas as pd
from dotenv import load_dotenv

BASE = Path(__file__).resolve().parent
load_dotenv(BASE / ".env")
from send_emails import build_batch, count_sent_today

FILE = BASE / "leads" / "mentis_leads_review.xlsx"

def key_status(name):
    value = (os.getenv(name) or "").strip().strip("\"'").strip()
    return f"{name}: {'present (length ' + str(len(value)) + ')' if value else 'missing'}"

def main():
    if not FILE.exists():
        print("Review workbook is missing.")
        return 1
    df = pd.read_excel(FILE).fillna("")
    print("Leads by Relevant:")
    print(df.get("Relevant", pd.Series(dtype=str)).astype(str).str.upper().value_counts().to_string())
    messages = df.get("Outreach Message", pd.Series([""] * len(df))).astype(str).str.strip()
    validation = df.get("Validation", pd.Series([""] * len(df))).astype(str).str.upper()
    print(f"\nMessages: PASS={sum(validation == 'PASS')} FAIL={sum(validation.str.startswith('FAIL'))} missing={sum(messages == '')}")
    print("\nGenerated by:")
    if "Generated By" in df:
        print(df["Generated By"].replace("", "(unknown)").value_counts().to_string())
        print("Per message:")
        for _, row in df[messages != ""].iterrows():
            provider = str(row.get("Generated By", "")).strip() or "(unknown)"
            print(f"  {str(row.get('Channel Name', '')).strip()} | {provider}")
    batch = build_batch(df)
    print(f"\nCurrent send batch ({len(batch)}):")
    for row in batch:
        name = str(row["Channel Name"]).strip()
        print(f"  {name} | {str(row['Email']).strip()} | Question about {name}")
    print(f"\nLIVE sends today: {count_sent_today()}")
    print("\nKeys:")
    print(key_status("GEMINI_API_KEY"))
    print(key_status("GROQ_API_KEY"))
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
